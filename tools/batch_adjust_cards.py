"""
妖斗牌 - 三区超模卡数值批量调整脚本
基于数值框架v2.1（派遣折扣0.7，在场效果2.0）
"""
import re
import os

def adjust_card(filepath, card_name, adjustments):
    """
    调整指定卡牌的数值。
    adjustments: dict, key为字段名(如'身材','费用','基础效果','反制点'), value为新值
    如果key为'_append_after_反制点', 则在反制点后追加内容
    """
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 找到卡牌区块
    pattern = rf'(### {re.escape(card_name)}\n.*?)(?=\n###|\Z)'
    match = re.search(pattern, content, re.DOTALL)
    if not match:
        print(f"  [WARN] 未找到卡牌: {card_name}")
        return False
    
    block = match.group(1)
    original_block = block
    
    for key, value in adjustments.items():
        if key.startswith('_append_after_'):
            field = key.replace('_append_after_', '')
            # 在指定字段后追加
            field_pattern = rf'(- \*\*{field}\*\*:.*?\n)(?=\n- \*\*|\n###|\Z)'
            field_match = re.search(field_pattern, block, re.DOTALL)
            if field_match:
                insertion = f"{field_match.group(1)}\n- **数值调整**: {value}\n"
                block = block[:field_match.start()] + insertion + block[field_match.end():]
        else:
            # 替换字段值
            field_pattern = rf'(- \*\*{re.escape(key)}\*\*: ).*'
            block = re.sub(field_pattern, rf'\g<1>{value}', block)
    
    if block != original_block:
        content = content[:match.start()] + block + content[match.end():]
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"  [OK] {card_name}: {list(adjustments.keys())}")
        return True
    else:
        print(f"  [SKIP] {card_name}: 无变化")
        return False

